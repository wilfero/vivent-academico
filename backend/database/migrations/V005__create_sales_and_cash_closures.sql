CREATE TABLE sales (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    company_id uuid NOT NULL REFERENCES companies (id),
    branch_id uuid NOT NULL REFERENCES branches (id),
    customer_id uuid REFERENCES customers (id),
    sale_number varchar(50) NOT NULL,
    sale_date timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    subtotal numeric(19,4) NOT NULL DEFAULT 0,
    discount_amount numeric(19,4) NOT NULL DEFAULT 0,
    tax_amount numeric(19,4) NOT NULL DEFAULT 0,
    total_amount numeric(19,4) NOT NULL DEFAULT 0,
    payment_method varchar(20) NOT NULL,
    status varchar(20) NOT NULL DEFAULT 'DRAFT',
    notes text,
    created_by uuid NOT NULL REFERENCES users (id),
    cancelled_by uuid REFERENCES users (id),
    cancel_reason text,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    cancelled_at timestamptz,
    CONSTRAINT uq_sales_company_number UNIQUE (company_id, sale_number),
    CONSTRAINT ck_sales_payment_method CHECK (payment_method IN ('CASH', 'CARD', 'TRANSFER', 'CREDIT', 'OTHER')),
    CONSTRAINT ck_sales_status CHECK (status IN ('DRAFT', 'CONFIRMED', 'CANCELLED')),
    CONSTRAINT ck_sales_subtotal CHECK (subtotal >= 0),
    CONSTRAINT ck_sales_discount_amount CHECK (discount_amount >= 0),
    CONSTRAINT ck_sales_tax_amount CHECK (tax_amount >= 0),
    CONSTRAINT ck_sales_total_amount CHECK (total_amount >= 0)
);

CREATE TABLE sale_details (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    sale_id uuid NOT NULL REFERENCES sales (id),
    product_id uuid NOT NULL REFERENCES products (id),
    presentation_id uuid NOT NULL REFERENCES product_presentations (id),
    barcode varchar(60),
    quantity_presentation numeric(19,6) NOT NULL,
    conversion_factor numeric(19,6) NOT NULL,
    quantity_base numeric(19,6) NOT NULL,
    unit_price numeric(19,4) NOT NULL,
    discount_amount numeric(19,4) NOT NULL DEFAULT 0,
    tax_amount numeric(19,4) NOT NULL DEFAULT 0,
    total_amount numeric(19,4) NOT NULL DEFAULT 0,
    fifo_cost_total numeric(19,4) NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_sale_details_quantity_presentation CHECK (quantity_presentation > 0),
    CONSTRAINT ck_sale_details_conversion_factor CHECK (conversion_factor > 0),
    CONSTRAINT ck_sale_details_quantity_base CHECK (quantity_base > 0),
    CONSTRAINT ck_sale_details_unit_price CHECK (unit_price >= 0),
    CONSTRAINT ck_sale_details_discount_amount CHECK (discount_amount >= 0),
    CONSTRAINT ck_sale_details_tax_amount CHECK (tax_amount >= 0),
    CONSTRAINT ck_sale_details_total_amount CHECK (total_amount >= 0),
    CONSTRAINT ck_sale_details_fifo_cost_total CHECK (fifo_cost_total >= 0)
);

CREATE TABLE cash_closures (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    company_id uuid NOT NULL REFERENCES companies (id),
    branch_id uuid NOT NULL REFERENCES branches (id),
    user_id uuid NOT NULL REFERENCES users (id),
    closure_date date NOT NULL,
    status varchar(20) NOT NULL DEFAULT 'OPEN',
    confirmed_sales_total numeric(19,4) NOT NULL DEFAULT 0,
    cancelled_sales_total numeric(19,4) NOT NULL DEFAULT 0,
    discount_total numeric(19,4) NOT NULL DEFAULT 0,
    expected_total numeric(19,4) NOT NULL DEFAULT 0,
    counted_total numeric(19,4) NOT NULL DEFAULT 0,
    difference_amount numeric(19,4) NOT NULL DEFAULT 0,
    notes text,
    approved_by uuid REFERENCES users (id),
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    closed_at timestamptz,
    approved_at timestamptz,
    CONSTRAINT uq_cash_closures_user_date UNIQUE (company_id, branch_id, user_id, closure_date),
    CONSTRAINT ck_cash_closures_status CHECK (status IN ('OPEN', 'CLOSED', 'APPROVED', 'REOPENED')),
    CONSTRAINT ck_cash_closures_confirmed_sales_total CHECK (confirmed_sales_total >= 0),
    CONSTRAINT ck_cash_closures_cancelled_sales_total CHECK (cancelled_sales_total >= 0),
    CONSTRAINT ck_cash_closures_discount_total CHECK (discount_total >= 0),
    CONSTRAINT ck_cash_closures_expected_total CHECK (expected_total >= 0),
    CONSTRAINT ck_cash_closures_counted_total CHECK (counted_total >= 0)
);

CREATE TABLE cash_closure_payments (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    cash_closure_id uuid NOT NULL REFERENCES cash_closures (id),
    payment_method varchar(20) NOT NULL,
    amount numeric(19,4) NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_cash_closure_payments_closure_method UNIQUE (cash_closure_id, payment_method),
    CONSTRAINT ck_cash_closure_payments_method CHECK (payment_method IN ('CASH', 'CARD', 'TRANSFER', 'CREDIT', 'OTHER')),
    CONSTRAINT ck_cash_closure_payments_amount CHECK (amount >= 0)
);
