CREATE TABLE purchases (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    company_id uuid NOT NULL REFERENCES companies (id),
    branch_id uuid NOT NULL REFERENCES branches (id),
    supplier_id uuid NOT NULL REFERENCES suppliers (id),
    purchase_number varchar(50) NOT NULL,
    supplier_invoice_number varchar(80),
    purchase_date date NOT NULL,
    payment_method varchar(20) NOT NULL,
    payment_type varchar(20) NOT NULL,
    subtotal numeric(19,4) NOT NULL DEFAULT 0,
    tax_amount numeric(19,4) NOT NULL DEFAULT 0,
    discount_amount numeric(19,4) NOT NULL DEFAULT 0,
    total_amount numeric(19,4) NOT NULL DEFAULT 0,
    status varchar(20) NOT NULL DEFAULT 'DRAFT',
    notes text,
    created_by uuid NOT NULL REFERENCES users (id),
    confirmed_by uuid REFERENCES users (id),
    voided_by uuid REFERENCES users (id),
    void_reason text,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    confirmed_at timestamptz,
    voided_at timestamptz,
    CONSTRAINT uq_purchases_company_number UNIQUE (company_id, purchase_number),
    CONSTRAINT ck_purchases_payment_method CHECK (payment_method IN ('CASH', 'CARD', 'TRANSFER', 'CHECK', 'OTHER')),
    CONSTRAINT ck_purchases_payment_type CHECK (payment_type IN ('CASH', 'CREDIT')),
    CONSTRAINT ck_purchases_status CHECK (status IN ('DRAFT', 'PENDING_APPROVAL', 'CONFIRMED', 'VOIDED')),
    CONSTRAINT ck_purchases_subtotal CHECK (subtotal >= 0),
    CONSTRAINT ck_purchases_tax_amount CHECK (tax_amount >= 0),
    CONSTRAINT ck_purchases_discount_amount CHECK (discount_amount >= 0),
    CONSTRAINT ck_purchases_total_amount CHECK (total_amount >= 0)
);

CREATE TABLE purchase_details (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    purchase_id uuid NOT NULL REFERENCES purchases (id),
    product_id uuid NOT NULL REFERENCES products (id),
    presentation_id uuid NOT NULL REFERENCES product_presentations (id),
    quantity_presentation numeric(19,6) NOT NULL,
    conversion_factor numeric(19,6) NOT NULL,
    quantity_base numeric(19,6) NOT NULL,
    unit_cost_presentation numeric(19,4) NOT NULL,
    unit_cost_base numeric(19,4) NOT NULL,
    subtotal numeric(19,4) NOT NULL DEFAULT 0,
    tax_amount numeric(19,4) NOT NULL DEFAULT 0,
    total_amount numeric(19,4) NOT NULL DEFAULT 0,
    expiration_date date,
    lot_number varchar(80),
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_purchase_details_quantity_presentation CHECK (quantity_presentation > 0),
    CONSTRAINT ck_purchase_details_conversion_factor CHECK (conversion_factor > 0),
    CONSTRAINT ck_purchase_details_quantity_base CHECK (quantity_base > 0),
    CONSTRAINT ck_purchase_details_unit_cost_presentation CHECK (unit_cost_presentation >= 0),
    CONSTRAINT ck_purchase_details_unit_cost_base CHECK (unit_cost_base >= 0),
    CONSTRAINT ck_purchase_details_subtotal CHECK (subtotal >= 0),
    CONSTRAINT ck_purchase_details_tax_amount CHECK (tax_amount >= 0),
    CONSTRAINT ck_purchase_details_total_amount CHECK (total_amount >= 0)
);
